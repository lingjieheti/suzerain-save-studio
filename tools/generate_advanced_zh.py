"""Regenerate the embedded Chinese glossary after editing the JSON dictionaries.
Python is needed only for translation maintenance, not app use or normal builds.
"""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parent.parent
merged={}
for name in ('advanced_zh_words_1.json','advanced_zh_words_2.json'):
    data=json.loads((root/'src'/name).read_text(encoding='utf-8-sig'))
    overlap=set(merged)&set(data)
    assert not overlap, f'Duplicate terms: {overlap}'
    merged.update(data)
assert len(merged)==2501, f'Expected 2501 glossary terms, got {len(merged)}'
lines=['#pragma once','#include <cstddef>','// Generated by tools/generate_advanced_zh.py. Display text only.',
       'struct AdvancedZhWord {const char* key; const wchar_t* zh;};',
       'inline constexpr AdvancedZhWord advancedZhWords[]={']
for key,value in sorted(merged.items()):
    assert value and any('\u3400'<=c<='\u9fff' for c in value), f'No Chinese gloss: {key}'
    lines.append('    {'+json.dumps(key)+',L'+json.dumps(value,ensure_ascii=False)+'},')
lines.append('};')
phrases=json.loads((root/'src/advanced_zh_phrases.json').read_text(encoding='utf-8'))
phrase_rows={}
longest=0
for phrase,caption in phrases.items():
    tokens=re.findall(r'[A-Z]+(?=[A-Z][a-z]|[0-9]|$)|[A-Z]?[a-z]+|[A-Z]+|[0-9]+',phrase)
    assert tokens and any('\u3400'<=c<='\u9fff' for c in caption)
    phrase_rows['|'.join(tokens)]=caption
    longest=max(longest,len(tokens))
lines.append(f'inline constexpr size_t advancedZhMaxPhraseWords={longest};')
lines.append('inline constexpr AdvancedZhWord advancedZhPhrases[]={')
for phrase,caption in sorted(phrase_rows.items()):
    lines.append('    {'+json.dumps(phrase)+',L'+json.dumps(caption,ensure_ascii=False)+'},')
lines.append('};')
segments={}
for name in ('advanced_zh_segments_1.json','advanced_zh_segments_2.json','advanced_zh_segments_3.json','advanced_zh_segments_extra.json'):
    entries=json.loads((root/'src'/name).read_text(encoding='utf-8'))
    for key,value in entries.items():
        assert any('\u3400'<=c<='\u9fff' for c in value), key
        if key in segments: assert segments[key]==value, f'Conflicting phrase: {key}'
        segments[key]=value
lines.append('inline constexpr AdvancedZhWord advancedZhSegments[]={')
for key,value in sorted(segments.items()):
    lines.append('    {'+json.dumps(key)+',L'+json.dumps(value,ensure_ascii=False)+'},')
lines.append('};')
(root/'src/advanced_zh_dictionary.hpp').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'Generated {len(merged)} Chinese glossary terms, {len(phrase_rows)} phrases and {len(segments)} complete segments.')
